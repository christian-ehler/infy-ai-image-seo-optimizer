# =============================================================================
# Validation & Utilities
# =============================================================================

def validate():
    """Validate all translations follow the rules."""
    errors = []
    for locale, data in PLUGIN_NAME_TRANSLATIONS.items():
        pt = data.get('page_title', '')
        ml = data.get('menu_label', '')

        # Check SEO is kept as-is
        if 'seo' in pt.lower() and 'SEO' not in pt:
            errors.append(f"{locale}: page_title has lowercase 'seo' — should be 'SEO'")

        # Check menu label length
        if len(ml) > 20:
            errors.append(f"{locale}: menu_label '{ml}' is {len(ml)} chars (max 20)")

        # Check no hyphens in page_title (except d'Imatges style apostrophes)
        if '-' in pt and "d'" not in pt:
            errors.append(f"{locale}: page_title '{pt}' contains hyphens — use spaces")

        # Check required fields
        if not pt or not ml:
            errors.append(f"{locale}: missing page_title or menu_label")

    if errors:
        print(f"ERRORS ({len(errors)}):")
        for e in errors:
            print(f"  ❌ {e}")
    else:
        print(f"✅ All {len(PLUGIN_NAME_TRANSLATIONS)} translations valid")

    return len(errors) == 0


def print_summary():
    """Print a summary table of all translations."""
    print(f"\n{'Locale':<10} {'AI/KI/IA':<6} {'Page Title':<45} {'Menu Label':<20} {'Len'}")
    print("-" * 90)
    for locale, data in PLUGIN_NAME_TRANSLATIONS.items():
        pt = data['page_title']
        ml = data['menu_label']
        # Detect which AI term is used
        if pt.startswith('KI ') or ml.startswith('KI '):
            ai = 'KI'
        elif 'IA' in pt[-5:] or 'IA' in ml[-5:]:
            ai = 'IA'
        else:
            ai = 'AI'
        print(f"{locale:<10} {ai:<6} {pt:<45} {ml:<20} {len(ml)}")


if __name__ == '__main__':
    validate()
    print_summary()
